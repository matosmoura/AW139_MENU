// Interpolação no gráfico de pairado: TQ + altitude -> altura h (retas);
// h + OAT -> ITT/NG máximos (entre as duas curvas de OAT vizinhas).
// Retorna null se o ponto cair fora da área coberta pelas curvas.
function hoverH(tq, alt) {
  var alts = Object.keys(HOVER.tq).map(Number).sort(function (a, b) { return a - b; });
  var lo = alts[0], hi = alts[alts.length - 1];
  for (var i = 0; i < alts.length - 1; i++) if (alt >= alts[i] && alt <= alts[i + 1]) { lo = alts[i]; hi = alts[i + 1]; break; }
  var f = (tq - 90) / 15;
  var hl = HOVER.tq[lo][0] + f * (HOVER.tq[lo][1] - HOVER.tq[lo][0]);
  var hh = HOVER.tq[hi][0] + f * (HOVER.tq[hi][1] - HOVER.tq[hi][0]);
  return hi === lo ? hl : hl + (alt - lo) / (hi - lo) * (hh - hl);
}
function hoverCurveAt(curve, h) {
  if (h < curve[0][0] - 1e-9 || h > curve[curve.length - 1][0] + 1e-9) return null;
  for (var i = 0; i < curve.length - 1; i++) {
    var a = curve[i], b = curve[i + 1];
    if (h >= a[0] - 1e-9 && h <= b[0] + 1e-9) return b[0] === a[0] ? a[1] : a[1] + (h - a[0]) / (b[0] - a[0]) * (b[1] - a[1]);
  }
  return curve[curve.length - 1][1];
}
function hoverMax(table, h, oat) {
  var oats = Object.keys(table).map(Number).sort(function (a, b) { return a - b; });
  var lo = oats[0], hi = oats[oats.length - 1];
  for (var i = 0; i < oats.length - 1; i++) if (oat >= oats[i] && oat <= oats[i + 1]) { lo = oats[i]; hi = oats[i + 1]; break; }
  var a = hoverCurveAt(table[lo], h), b = hoverCurveAt(table[hi], h);
  if (a === null || b === null) return null;
  return hi === lo ? a : a + (oat - lo) / (hi - lo) * (b - a);
}

